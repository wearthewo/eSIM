"""Batches: one per upload that passed /validate, the parts generated for it, the
duplicate check across batches, and the History page's query.

What is stored: the organization, the user, the time, the sanitized file name, counts
and the status, plus HMAC fingerprints (``app.db.fingerprints``) of each generated row's
ICCID and activation code. Never a code, a customer name or email, the file or a PDF.

Duplicate check: a row whose ICCID or activation code was generated by another batch of
the same organization in the last ``DUPLICATE_WINDOW`` is an error. Fingerprints of the
batch itself never count, so retries and "download again" are not duplicates. Lookups
are one query per kind per ``LOOKUP_CHUNK`` fingerprints (the unique index on
organization, kind and fingerprint serves them), never one per row.

Recording a part (``record_part``) holds a per-organization advisory lock and checks the
part's rows again inside it, so two batches with the same codes generated at the same
moment cannot both succeed. Voiding (``void``) takes the same lock, and ``record_part``
refuses a voided batch inside it, so a part finishing during a void cannot re-add
fingerprints.

Daily quota: ``usage`` counts the rows generated per organization and UTC day. A part
not recorded yet is refused (``QuotaExceeded``) inside ``record_part``, under the same
lock, when it would take the day over ``organizations.daily_row_quota``; parts already
recorded never count again. /validate and /generate also check before any work
(``check_quota``), and every refusal writes a ``quota_exceeded`` audit row.

Continuing (``continuable``): a re-upload whose only duplicates are the rows of ONE
unfinished batch (partial or incomplete) of the organization, with the same row count,
and with every fingerprint of that batch in the same part of the new file (by the
batch's own part size, ``Batch.chunk_rows``), reuses that batch instead of failing.

Every function takes an open SQLAlchemy ``Session`` and leaves committing to the caller;
``now`` is timezone-aware UTC.
"""

