def _count(result: object) -> int:
    return int(getattr(result, "rowcount", 0) or 0)


def purge(db: Session, *, now: dt.datetime) -> dict[str, int]:
    """The daily purge's part for batches (``app.auth.retention.purge``):

    - fingerprints older than ``DUPLICATE_WINDOW`` are deleted;
    - ``partial`` batches created over ``STALE_AFTER`` ago become ``incomplete``;
    - ``validated`` batches (nothing generated, so no fingerprints) created over
      ``STALE_AFTER`` ago are deleted.
    """
    stale = now - STALE_AFTER
    return {
        "code_fingerprints": _count(
            db.execute(
                delete(CodeFingerprint)
                .where(CodeFingerprint.created_at < now - DUPLICATE_WINDOW)
                .execution_options(synchronize_session=False)
            )
        ),
        "batches_incomplete": _count(
            db.execute(
                update(Batch)
                .where(Batch.status == BatchStatus.PARTIAL, Batch.created_at < stale)
                .values(status=BatchStatus.INCOMPLETE)
                .execution_options(synchronize_session=False)
            )
        ),
        "batches_unused": _count(
            db.execute(
                delete(Batch)
                .where(Batch.status == BatchStatus.VALIDATED, Batch.created_at < stale)
                .execution_options(synchronize_session=False)
            )
        ),
    }
