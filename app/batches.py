DUPLICATE_WINDOW = dt.timedelta(days=365)  # "the last 12 months"; also the fingerprint TTL
STALE_AFTER = dt.timedelta(hours=24)
# Fingerprints per lookup query. Measured on 1,000,000 rows: up to ~2,000 values
# PostgreSQL probes the unique index; with 10,000 it switches to a full table scan.
LOOKUP_CHUNK = 1_000
INSERT_CHUNK = 5_000  # fingerprint rows per INSERT
HISTORY_PAGE_SIZE = 50
SUMMARY_GROUPS = 5  # earlier batches named in the "already used" summary
DEFAULT_FILE_NAME = "upload"

# pg_advisory_xact_lock(class, organization_id): one lock per organization, distinct from
# the single-key locks (retention uses 0x6553_0002).
_PART_LOCK_CLASS = 0x6553_0003

MSG_ALREADY_USED = "Already used in batch '{file_name}' on {when}"
CONTINUABLE = frozenset({BatchStatus.PARTIAL, BatchStatus.INCOMPLETE})

# audit_log.action values
BATCH_VOIDED = "batch_voided"
QUOTA_EXCEEDED = "quota_exceeded"

MSG_QUOTA = (
    "Daily limit reached: {used} of {quota} rows used today. "
    "The limit resets at {reset} Greek time."
)


class BatchVoided(Exception):
    """The batch was voided: nothing more can be generated for it."""


@dataclass(frozen=True, slots=True)
class DailyUsage:
    """Rows the organization generated today (UTC day) and its daily row quota."""

    used: int
    quota: int

    @property
    def remaining(self) -> int:
        return max(0, self.quota - self.used)


class QuotaExceeded(Exception):
    """Generating the rows asked for would take the organization over its daily quota."""

    def __init__(self, usage: DailyUsage) -> None:
        super().__init__("daily row quota exceeded")
        self.usage = usage


class AlreadyVoided(Exception):
    """``void`` was asked for a batch that is voided already."""


# (kind, field of EsimRecord and of the issue, issue code)
_KINDS: tuple[tuple[FingerprintKind, str, str], ...] = (
    (FingerprintKind.ICCID, "iccid", "already_used_iccid"),
    (FingerprintKind.ACTIVATION, "activation_code", "already_used_activation_code"),
)
_FIELD_ORDER = {field: i for i, (_, field, _) in enumerate(_KINDS)}
_PATH_SEPARATORS = re.compile(r"[\\/]")


# --- File names ----------------------------------------------------------------------------


def sanitize_file_name(name: str) -> str:
    """The name to keep: no folders, NFC, no control/format characters, single spaces,
    at most ``MAX_FILE_NAME_CHARS`` characters; ``"upload"`` if nothing is left."""
    base = _PATH_SEPARATORS.split(name)[-1]
    base = unicodedata.normalize("NFC", base)
    base = "".join(" " if ch.isspace() else ch for ch in base if ch.isspace() or not _is_other(ch))
    base = " ".join(base.split())[:MAX_FILE_NAME_CHARS].strip()
    return base or DEFAULT_FILE_NAME


def _is_other(ch: str) -> bool:
    """Unicode category C*: control, format, surrogate, private use, unassigned."""
    return unicodedata.category(ch).startswith("C")


# --- Duplicate check -----------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class UsedGroup:
    """Rows of the upload already generated by one earlier batch."""

    batch_id: int
    file_name: str
    created_at: dt.datetime
    rows: int

    @property
    def when(self) -> str:
        return format_athens(self.created_at)


@dataclass(frozen=True, slots=True)
class UsedSummary:
    """``rows`` rows were used before; ``groups`` are the largest earlier batches."""

    rows: int
    groups: tuple[UsedGroup, ...]
    more: bool  # rows of further earlier batches not listed


@dataclass(frozen=True, slots=True)
class UsedCheck:
    issues: list[ValidationIssue]
    summary: UsedSummary | None
    # When something was found: the flagged rows per earlier batch, and the file's
    # fingerprints ({kind: {fingerprint: [row numbers]}}), for ``continuable``.
    rows_by_batch: dict[int, set[int]] = dataclasses.field(default_factory=dict)
    digests: dict[FingerprintKind, dict[bytes, list[int]]] = dataclasses.field(default_factory=dict)

    @property
    def found(self) -> bool:
        return bool(self.issues)


NOTHING_USED = UsedCheck(issues=[], summary=None)


def _digests(
    organization_id: int, records: Iterable[EsimRecord], key: bytes
) -> dict[FingerprintKind, dict[bytes, list[int]]]:
    """``{kind: {fingerprint: [row numbers]}}`` for the records' non-empty values."""
    out: dict[FingerprintKind, dict[bytes, list[int]]] = {}
    for kind, field, _ in _KINDS:
        digest_of = fingerprinter(organization_id, kind, key=key)
        by_digest: dict[bytes, list[int]] = {}
        for record in records:
            value = getattr(record, field)
            if value:
                by_digest.setdefault(digest_of(value), []).append(record.row_number)
        out[kind] = by_digest
    return out


def _matches(
    db: Session,
    organization_id: int,
    kind: FingerprintKind,
    digests: Sequence[bytes],
    *,
    since: dt.datetime,
    exclude_batch_id: int | None,
) -> list[tuple[bytes, int, str, dt.datetime]]:
    """``(fingerprint, batch id, file name, batch created_at)`` of earlier uses."""
    found: list[tuple[bytes, int, str, dt.datetime]] = []
    for i in range(0, len(digests), LOOKUP_CHUNK):
        chunk = list(digests[i : i + LOOKUP_CHUNK])
        query = (
            select(CodeFingerprint.fingerprint, Batch.id, Batch.file_name, Batch.created_at)
            .join(Batch, Batch.id == CodeFingerprint.batch_id)
            .where(
                CodeFingerprint.organization_id == organization_id,
                CodeFingerprint.kind == kind,
                CodeFingerprint.fingerprint
                == any_(bindparam("digests", chunk, type_=ARRAY(BYTEA))),
                CodeFingerprint.created_at >= since,
            )
        )
        if exclude_batch_id is not None:
            query = query.where(CodeFingerprint.batch_id != exclude_batch_id)
        found += [(fp, bid, name, at) for fp, bid, name, at in db.execute(query).all()]
    return found


def find_used(
    db: Session,
    organization_id: int,
    records: Sequence[EsimRecord],
    *,
    key: bytes,
    now: dt.datetime,
    exclude_batch_id: int | None = None,
) -> UsedCheck:
    """Rows whose ICCID or activation code another batch of the organization generated
    in the last ``DUPLICATE_WINDOW``: one error per row and field, naming the earlier
    batch's file and time (never the value), plus a summary by earlier batch."""
    if not records:
        return NOTHING_USED
    since = now - DUPLICATE_WINDOW
    issues: list[ValidationIssue] = []
    rows_by_batch: dict[int, set[int]] = {}
    batches: dict[int, tuple[str, dt.datetime]] = {}
    all_digests = _digests(organization_id, records, key)
    for kind, field, code in _KINDS:
        by_digest = all_digests[kind]
        for digest, batch_id, file_name, created_at in _matches(
            db,
            organization_id,
            kind,
            list(by_digest),
            since=since,
            exclude_batch_id=exclude_batch_id,
        ):
            batches[batch_id] = (file_name, created_at)
            message = MSG_ALREADY_USED.format(file_name=file_name, when=format_athens(created_at))
            for row in by_digest[digest]:
                rows_by_batch.setdefault(batch_id, set()).add(row)
                issues.append(ValidationIssue(row, field, code, message))
    if not issues:
        return NOTHING_USED
    issues.sort(key=lambda issue: (issue.row_number, _FIELD_ORDER[issue.field]))
    return UsedCheck(
        issues=issues,
        summary=_summary(rows_by_batch, batches),
        rows_by_batch=rows_by_batch,
        digests=all_digests,
    )


def _summary(
    rows_by_batch: dict[int, set[int]], batches: dict[int, tuple[str, dt.datetime]]
) -> UsedSummary:
    groups = sorted(
        (
            UsedGroup(batch_id, batches[batch_id][0], batches[batch_id][1], len(rows))
            for batch_id, rows in rows_by_batch.items()
        ),
        key=lambda g: (-g.rows, -g.created_at.timestamp(), -g.batch_id),
    )
    all_rows = set().union(*rows_by_batch.values())
    return UsedSummary(
        rows=len(all_rows),
        groups=tuple(groups[:SUMMARY_GROUPS]),
        more=len(groups) > SUMMARY_GROUPS,
    )


def merge(report: ValidationReport, check: UsedCheck) -> ValidationReport:
    """``report`` with the check's errors added and their rows taken out of ``valid``."""
    if not check.found:
        return report
    flagged = {issue.row_number for issue in check.issues}
    return ValidationReport(
        valid=[r for r in report.valid if r.row_number not in flagged],
        issues=[*report.issues, *check.issues],
    )


# --- Continuing an unfinished batch ----------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Continuation:
    """The unfinished batch a re-uploaded file continues."""

    batch_id: int
    file_name: str
    created_at: dt.datetime
    parts: int
    parts_downloaded: int
    chunk_rows: int
    downloaded: tuple[int, ...]  # part numbers in batch_parts

    @property
    def when(self) -> str:
        return format_athens(self.created_at)


def downloaded_parts(db: Session, batch_id: int) -> tuple[int, ...]:
    return tuple(
        db.scalars(
            select(BatchPart.part).where(BatchPart.batch_id == batch_id).order_by(BatchPart.part)
        ).all()
    )


def continuable(
    db: Session,
    organization_id: int,
    report: ValidationReport,
    check: UsedCheck,
    *,
    row_count: int,
) -> Continuation | None:
    """The unfinished batch this upload continues, or ``None`` (the duplicates stand).

    ``report`` is the file's own report (before ``merge``), ``check`` the result of
    ``find_used`` on it. A match needs all of: no other errors in the file; every
    flagged row belongs to one earlier batch B of the organization; B is partial or
    incomplete with the same row count; and every fingerprint of B is in the file, in a
    row of the same part (by B's own part size). Fingerprints without a part (recorded
    before parts were stored) never match.
    """
    if not check.found or len(check.rows_by_batch) != 1 or report.errors:
        return None
    (batch_id,) = check.rows_by_batch
    batch = scoped_batch(db, organization_id, batch_id)
    if batch is None or batch.status not in CONTINUABLE or batch.row_count != row_count:
        return None
    if pipeline.part_count(row_count, batch.chunk_rows) != batch.parts:
        return None
    part_of_row = {
        record.row_number: pipeline.part_of(index, batch.chunk_rows)
        for index, record in enumerate(report.valid)
    }
    stored = db.execute(
        select(CodeFingerprint.kind, CodeFingerprint.fingerprint, CodeFingerprint.part).where(
            CodeFingerprint.batch_id == batch_id
        )
    ).all()
    if not stored:
        return None
    for kind, digest, part in stored:
        rows = check.digests.get(kind, {}).get(digest)
        if part is None or not rows or len(rows) != 1 or part_of_row.get(rows[0]) != part:
            return None
    return Continuation(
        batch_id=batch.id,
        file_name=batch.file_name,
        created_at=batch.created_at,
        parts=batch.parts,
        parts_downloaded=batch.parts_downloaded,
        chunk_rows=batch.chunk_rows,
        downloaded=downloaded_parts(db, batch.id),
    )


# --- Batches -------------------------------------------------------------------------------


def create_batch(
    db: Session,
    *,
    organization_id: int,
    user_id: int,
    file_name: str,
    row_count: int,
    parts: int,
    warning_count: int,
    now: dt.datetime,
    chunk_rows: int | None = None,
) -> int:
    """A ``validated`` batch for an upload that passed; returns its id.

    ``chunk_rows`` defaults to today's ``GENERATE_CHUNK_ROWS``; the batch keeps it.
    """
    batch = Batch(
        organization_id=organization_id,
        user_id=user_id,
        created_at=now,
        file_name=sanitize_file_name(file_name),
        row_count=row_count,
        parts=parts,
        chunk_rows=pipeline.GENERATE_CHUNK_ROWS if chunk_rows is None else chunk_rows,
        warning_count=warning_count,
        status=BatchStatus.VALIDATED,
    )
    db.add(batch)
    db.flush()
    return batch.id


def scoped_batch(db: Session, organization_id: int, batch_id: int) -> Batch | None:
    """The batch if it belongs to the organization, else ``None`` (the route answers 404)."""
    return db.scalars(
        select(Batch).where(Batch.id == batch_id, Batch.organization_id == organization_id)
    ).first()


def _lock_organization(db: Session, organization_id: int) -> None:
    """The organization's batch lock, held until the transaction ends (record_part, void)."""
    db.execute(
        select(
            func.pg_advisory_xact_lock(
                literal(_PART_LOCK_CLASS, Integer), cast(literal(organization_id), Integer)
            )
        )
    )


def _status(batch: Batch) -> BatchStatus:
    return BatchStatus.COMPLETED if batch.parts_downloaded >= batch.parts else BatchStatus.PARTIAL


def record_part(
    db: Session,
    organization_id: int,
    batch_id: int,
    part: int,
    records: Sequence[EsimRecord],
    *,
    key: bytes,
    now: dt.datetime,
) -> UsedCheck:
    """Record that ``part`` of the batch was generated from ``records``.

    Under the organization's lock: refuse a voided batch (``BatchVoided``); check the
    records against other batches again (a hit is returned and nothing is recorded).
    Then, the first time this part is recorded only, add the rows' fingerprints (with
    the part number), count the part and add the rows to today's usage. The status
    becomes partial or completed (also from incomplete or failed). Retries of a part
    change nothing else.

    Daily quota: a part not recorded yet whose rows would take today's usage over the
    organization's quota raises ``QuotaExceeded`` (nothing is recorded; the caller's
    transaction rolls back). Under the lock, so two parts at once cannot both pass. A part
    already recorded (downloaded again) is never counted again or refused.
    """
    _lock_organization(db, organization_id)
    batch = db.scalars(
        select(Batch)
        .where(Batch.id == batch_id, Batch.organization_id == organization_id)
        .with_for_update()
    ).one()
    if batch.status == BatchStatus.VOIDED:
        raise BatchVoided
    if part not in downloaded_parts(db, batch_id):
        check_quota(db, organization_id, len(records), now=now)
    check = find_used(db, organization_id, records, key=key, now=now, exclude_batch_id=batch_id)
    if check.found:
        return check

    new_part = db.execute(
        pg_insert(BatchPart)
        .values(batch_id=batch_id, part=part, created_at=now)
        .on_conflict_do_nothing()
        .returning(BatchPart.part)
    ).first()
    if new_part is not None:
        _add_fingerprints(db, organization_id, batch_id, records, key=key, now=now, part=part)
        batch.parts_downloaded = min(batch.parts_downloaded + 1, batch.parts)
        _add_usage(db, organization_id, len(records), now=now)
    batch.status = _status(batch)
    db.flush()
    return NOTHING_USED


def _add_fingerprints(
    db: Session,
    organization_id: int,
    batch_id: int,
    records: Sequence[EsimRecord],
    *,
    key: bytes,
    now: dt.datetime,
    part: int | None = None,
) -> None:
    values = [
        {
            "organization_id": organization_id,
            "kind": kind,
            "fingerprint": digest,
            "batch_id": batch_id,
            "created_at": now,
            "part": part,
        }
        for kind, by_digest in _digests(organization_id, records, key).items()
        for digest in by_digest
    ]
    # Chunks keep each statement under PostgreSQL's 65,535 bind parameters (5 per row).
    for i in range(0, len(values), INSERT_CHUNK):
        statement = pg_insert(CodeFingerprint).values(values[i : i + INSERT_CHUNK])
        # A row outside the window (not purged yet) is taken over; rows of this batch and
        # rows inside the window (impossible after the check under the lock) stay as they are.
        statement = statement.on_conflict_do_update(
            index_elements=[
                CodeFingerprint.organization_id,
                CodeFingerprint.kind,
                CodeFingerprint.fingerprint,
            ],
            set_={
                "batch_id": statement.excluded.batch_id,
                "created_at": statement.excluded.created_at,
                "part": statement.excluded.part,
            },
            where=CodeFingerprint.created_at < now - DUPLICATE_WINDOW,
        )
        db.execute(statement)


def _add_usage(db: Session, organization_id: int, rows: int, *, now: dt.datetime) -> None:
    statement = pg_insert(Usage).values(
        organization_id=organization_id, day=now.astimezone(dt.UTC).date(), rows_generated=rows
    )
    db.execute(
        statement.on_conflict_do_update(
            index_elements=[Usage.organization_id, Usage.day],
            set_={"rows_generated": Usage.rows_generated + statement.excluded.rows_generated},
        )
    )


# --- Daily quota ---------------------------------------------------------------------------


def daily_usage(db: Session, organization_id: int, *, now: dt.datetime) -> DailyUsage:
    """Rows generated today (the UTC day of ``now``, as ``_add_usage`` counts) and the quota."""
    row = db.execute(
        select(Organization.daily_row_quota, func.coalesce(Usage.rows_generated, 0))
        .outerjoin(
            Usage,
            (Usage.organization_id == Organization.id)
            & (Usage.day == now.astimezone(dt.UTC).date()),
        )
        .where(Organization.id == organization_id)
    ).one()
    return DailyUsage(used=int(row[1]), quota=int(row[0]))


def check_quota(db: Session, organization_id: int, rows: int, *, now: dt.datetime) -> DailyUsage:
    """Today's usage, if ``rows`` more fit in the quota; else raises ``QuotaExceeded``.

    Reaching the quota exactly is allowed. A quota of 0 refuses every row.
    """
    usage = daily_usage(db, organization_id, now=now)
    if usage.used + rows > usage.quota:
        raise QuotaExceeded(usage)
    return usage


def quota_message(usage: DailyUsage, now: dt.datetime) -> str:
    """The refusal to show, with the reset time in Greek time (02:00 or 03:00, by DST)."""
    return MSG_QUOTA.format(
        used=thousands(usage.used), quota=thousands(usage.quota), reset=daily_reset_athens(now)
    )


def audit_quota_exceeded(
    db: Session,
    *,
    now: dt.datetime,
    user_id: int | None,
    organization_id: int,
    ip: IpPrefix | None,
    batch_id: int | None = None,
) -> None:
    """A ``quota_exceeded`` audit row: who, which organization and batch. No counts, no codes."""
    accounts.audit(
        db,
        QUOTA_EXCEEDED,
        AuditOutcome.FAILURE,
        now=now,
        user_id=user_id,
        organization_id=organization_id,
        ip=ip,
        target_batch_id=batch_id,
    )


def part_rows(row_count: int, part: int, chunk_rows: int) -> int:
    """Rows in ``part`` (1-based) of an upload of ``row_count`` rows in parts of ``chunk_rows``."""
    return max(0, min(chunk_rows, row_count - (part - 1) * chunk_rows))


def remaining_rows(row_count: int, chunk_rows: int, parts: int, downloaded: Iterable[int]) -> int:
    """Rows in the parts not generated yet (parts in ``downloaded`` never count again)."""
    done = set(downloaded)
    return sum(
        part_rows(row_count, part, chunk_rows) for part in range(1, parts + 1) if part not in done
    )


def mark_failed(db: Session, organization_id: int, batch_id: int, report: ValidationReport) -> None:
    """A /generate request for the batch found errors: status ``failed``, with the counts."""
    db.execute(
        update(Batch)
        .where(Batch.id == batch_id, Batch.organization_id == organization_id)
        .values(
            status=BatchStatus.FAILED,
            error_count=len(report.errors),
            warning_count=len(report.warnings),
        )
    )


# --- Voiding -------------------------------------------------------------------------------


def voidable_batch(db: Session, actor: CurrentUser, batch_id: int) -> Batch | None:
    """The batch if ``actor`` may void it, else ``None`` (the route answers 404).

    Superadmins: any batch. Owners: their own organization's. Members: none. Batches only
    checked (``validated``) are not listed in History and cannot be voided.
    """
    batch = db.get(Batch, batch_id)
    if batch is None or batch.status == BatchStatus.VALIDATED:
        return None
    if actor.is_superadmin:
        return batch
    if actor.role == Role.OWNER and actor.organization_id == batch.organization_id:
        return batch
    return None


def void(
    db: Session, actor: CurrentUser, batch_id: int, *, ip: IpPrefix | None, now: dt.datetime
) -> bool:
    """Void a batch ``actor`` may void: its fingerprints are deleted (its codes are
    accepted again), it is marked voided, and a ``batch_voided`` audit row is added.

    Holds the organization's batch lock (as ``record_part``), so a part being recorded
    either finishes first (and its fingerprints are deleted here) or is refused after.
    Returns False if out of scope; raises ``AlreadyVoided``.
    """
    found = voidable_batch(db, actor, batch_id)
    if found is None:
        return False
    organization_id = found.organization_id
    _lock_organization(db, organization_id)
    batch = db.scalars(
        select(Batch)
        .where(Batch.id == batch_id)
        .with_for_update()
        .execution_options(populate_existing=True)
    ).one()
    if batch.status == BatchStatus.VOIDED:
        raise AlreadyVoided
    db.execute(
        delete(CodeFingerprint)
        .where(CodeFingerprint.batch_id == batch_id)
        .execution_options(synchronize_session=False)
    )
    batch.status = BatchStatus.VOIDED
    batch.voided_at = now
    batch.voided_by = actor.user_id
    accounts.audit(
        db,
        BATCH_VOIDED,
        AuditOutcome.SUCCESS,
        now=now,
        user_id=actor.user_id,
        organization_id=organization_id,
        ip=ip,
        target_batch_id=batch_id,
    )
    db.flush()
    return True


# --- History -------------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class HistoryRow:
    id: int
    created_at: dt.datetime
    user_email: str | None
    organization_name: str | None
    file_name: str
    row_count: int
    parts: int
    parts_downloaded: int
    warning_count: int
    error_count: int
    status: BatchStatus
    voided_at: dt.datetime | None = None
    voided_by_email: str | None = None

    @property
    def voided(self) -> bool:
        return self.status == BatchStatus.VOIDED


@dataclass(frozen=True, slots=True)
class HistoryPage:
    rows: list[HistoryRow]
    total: int
    page: int
    pages: int


def history(
    db: Session,
    *,
    organization_id: int | None,
    start: dt.datetime,
    end: dt.datetime,
    page: int,
) -> HistoryPage:
    """Batches created in ``[start, end)``, newest first, ``HISTORY_PAGE_SIZE`` per page.

    ``organization_id=None`` means every organization (superadmin only). ``validated``
    batches (nothing generated yet) are left out. A page past the end shows the last.
    """
    conditions = [
        Batch.status != BatchStatus.VALIDATED,
        Batch.created_at >= start,
        Batch.created_at < end,
    ]
    if organization_id is not None:
        conditions.append(Batch.organization_id == organization_id)
    total = db.scalar(select(func.count(Batch.id)).where(*conditions)) or 0
    pages = max(1, math.ceil(total / HISTORY_PAGE_SIZE))
    page = min(max(page, 1), pages)
    voider = aliased(User)
    query = (
        select(Batch, User.email, Organization.name, voider.email)
        .outerjoin(User, User.id == Batch.user_id)
        .outerjoin(voider, voider.id == Batch.voided_by)
        .join(Organization, Organization.id == Batch.organization_id)
        .where(*conditions)
        .order_by(Batch.created_at.desc(), Batch.id.desc())
        .limit(HISTORY_PAGE_SIZE)
        .offset((page - 1) * HISTORY_PAGE_SIZE)
    )
    rows = [
        HistoryRow(
            id=b.id,
            created_at=b.created_at,
            user_email=email,
            organization_name=org_name,
            file_name=b.file_name,
            row_count=b.row_count,
            parts=b.parts,
            parts_downloaded=b.parts_downloaded,
            warning_count=b.warning_count,
            error_count=b.error_count,
            status=b.status,
            voided_at=b.voided_at,
            voided_by_email=voided_by,
        )
        for b, email, org_name, voided_by in db.execute(query).all()
    ]
    return HistoryPage(rows=rows, total=total, page=page, pages=pages)


def organizations(db: Session) -> list[tuple[int, str]]:
    """``(id, name)`` of every organization, for the superadmin's filter."""
    return [
        (org_id, name)
        for org_id, name in db.execute(
            select(Organization.id, Organization.name).order_by(
                func.lower(Organization.name), Organization.id
            )
        ).all()
    ]


