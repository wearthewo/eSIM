class AccessRequest(Base):
    """A "Request access" form submission (the requester's details, kept 30 days)."""

    __tablename__ = "access_requests"
    __table_args__ = (
        CheckConstraint(f"char_length(note) <= {MAX_NOTE_CHARS}", name="note_length"),
    )

    id: Mapped[int] = _id()
    company_name: Mapped[str] = mapped_column(String(MAX_NAME_CHARS))
    contact_name: Mapped[str] = mapped_column(String(MAX_NAME_CHARS))
