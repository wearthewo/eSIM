DEFAULT_DAILY_ROW_QUOTA = 20_000
DIGEST_BYTES = 32  # SHA-256 / HMAC-SHA256
MAX_EMAIL_CHARS = 254
MAX_NAME_CHARS = 200
MAX_NOTE_CHARS = 2000
MAX_ACTION_CHARS = 64
MAX_FILE_NAME_CHARS = 200
# app.core.pipeline.GENERATE_CHUNK_ROWS when batches.chunk_rows was added (migration 0005).
DEFAULT_CHUNK_ROWS = 500
# Match app/web/routes.py (MAX_COMPANY_CHARS, MAX_FOOTER_CHARS, MAX_LOGO_BYTES).
MAX_BRANDING_COMPANY_CHARS = 100
MAX_BRANDING_FOOTER_CHARS = 200
MAX_LOGO_BYTES = 500 * 1024
PNG_SIGNATURE_HEX = "89504e470d0a1a0a"
DEFAULT_PRIMARY_HEX = "#000000"


class Role(enum.StrEnum):
    OWNER = "owner"
    MEMBER = "member"


class AccessRequestStatus(enum.StrEnum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"


class VolumeBand(enum.StrEnum):
    """Expected eSIMs per month, as chosen on the "Request access" form."""

    UNDER_1K = "under_1k"
    FROM_1K_TO_10K = "1k_10k"
    FROM_10K_TO_100K = "10k_100k"
    OVER_100K = "over_100k"


class FingerprintKind(enum.StrEnum):
    ICCID = "iccid"
    ACTIVATION = "activation"


class BatchStatus(enum.StrEnum):
    """Where a batch stands (``app.batches``).

    - validated: the file passed /validate; no part generated yet (hidden from History,
      deleted by the daily purge after 24 hours).
    - partial: some parts generated. completed: every part generated.
    - incomplete: still partial 24 hours after it was created (set by the daily purge).
    - failed: a /generate request for it found errors.
    - voided: an owner or superadmin voided it (none of its eSIMs were sent); its
      fingerprints are deleted, so its codes are accepted again. Final.
    A part generated later moves an incomplete or failed batch back to partial/completed.
    """

    VALIDATED = "validated"
    PARTIAL = "partial"
    COMPLETED = "completed"
    INCOMPLETE = "incomplete"
    FAILED = "failed"
    VOIDED = "voided"


class AuditOutcome(enum.StrEnum):
    SUCCESS = "success"
    FAILURE = "failure"


def _enum(cls: type[enum.StrEnum], name: str) -> Enum:
    """``VARCHAR`` + ``CHECK`` storing the member values (``"owner"``, not ``"OWNER"``)."""
    return Enum(
        cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=16,
        values_callable=lambda members: [m.value for m in members],
        validate_strings=True,
    )


def _id() -> MappedColumn[int]:
    return mapped_column(BigInteger, Identity(), primary_key=True)


def _created_at(*, index: bool = False) -> MappedColumn[dt.datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), index=index)


def _fk(target: str, ondelete: str, *, nullable: bool, index: bool = False) -> MappedColumn[Any]:
    return mapped_column(
        BigInteger, ForeignKey(target, ondelete=ondelete), nullable=nullable, index=index
    )


def _digest_check(column: str) -> CheckConstraint:
    return CheckConstraint(f"octet_length({column}) = {DIGEST_BYTES}", name=f"{column}_length")


class Organization(Base):
    __tablename__ = "organizations"
    __table_args__ = (CheckConstraint("daily_row_quota >= 0", name="daily_row_quota_nonnegative"),)

    id: Mapped[int] = _id()
    name: Mapped[str] = mapped_column(String(MAX_NAME_CHARS))
    daily_row_quota: Mapped[int] = mapped_column(
        Integer, default=DEFAULT_DAILY_ROW_QUOTA, server_default=str(DEFAULT_DAILY_ROW_QUOTA)
    )
    disabled: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    created_at: Mapped[dt.datetime] = _created_at()


class User(Base):
    """A login. ``email`` is unique case-insensitively (``lower(email)`` index).

    Two-factor authentication (``app.auth.mfa``): ``mfa_secret`` is the TOTP secret,
    encrypted (never plaintext); ``mfa_enabled_at`` is set once the user confirmed a code
    (NULL: 2FA is off, and a secret without it is an enrolment not confirmed yet);
    ``mfa_last_step`` is the last accepted 30-second step, so a code cannot be used twice.
    """

    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint(
            "is_superadmin OR organization_id IS NOT NULL",
            name="organization_required_unless_superadmin",
        ),
        CheckConstraint(
            "mfa_enabled_at IS NULL OR mfa_secret IS NOT NULL", name="mfa_enabled_needs_secret"
        ),
    )

    id: Mapped[int] = _id()
    email: Mapped[str] = mapped_column(String(MAX_EMAIL_CHARS))
    password_hash: Mapped[str | None] = mapped_column(Text)  # NULL until the invite is accepted
    organization_id: Mapped[int | None] = _fk(
        "organizations.id", "CASCADE", nullable=True, index=True
    )
    role: Mapped[Role] = mapped_column(_enum(Role, "role"), default=Role.MEMBER)
    is_superadmin: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    disabled: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    created_at: Mapped[dt.datetime] = _created_at()
    last_login_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))
    mfa_secret: Mapped[bytes | None] = mapped_column(LargeBinary)
    mfa_enabled_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))
    mfa_last_step: Mapped[int | None] = mapped_column(BigInteger)


Index("uq_users_email_lower", func.lower(User.email), unique=True)


class MfaRecoveryCode(Base):
    """A one-time recovery code for two-factor login: only its HMAC (``app.auth.mfa``)."""

    __tablename__ = "mfa_recovery_codes"
