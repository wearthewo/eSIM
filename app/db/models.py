"""SQLAlchemy models: metadata only.

No table has a column for activation codes, matching IDs, confirmation codes,
uploaded files, PDFs, customer names or customer emails. Codes are only ever
stored as HMAC fingerprints (``code_fingerprints``, see ``app.db.fingerprints``).
Two-factor secrets are stored only AES-GCM encrypted with MFA_KEY (``users.mfa_secret``)
and recovery codes only as HMACs (``mfa_recovery_codes``), see ``app.auth.mfa``.
A batch keeps the uploaded file's sanitized name (for the History page), never its content.

Conventions:

- Primary keys are ``BIGINT GENERATED BY DEFAULT AS IDENTITY``.
- Times are ``timestamptz`` (UTC) with ``now()`` server defaults; ``usage.day`` is a UTC date.
- Enumerations are ``VARCHAR`` + ``CHECK`` (not native PG enums), so adding a value
  is a plain constraint change.
- Token and fingerprint columns hold 32-byte digests (``CHECK octet_length = 32``).
- ``ON DELETE`` is enforced by the database (no ORM cascades): data owned by an
  organization is deleted with it, a user's sessions are deleted with the user,
  and history (batches, audit log, who invited / handled what) survives with the
  user or organization reference set to NULL. Organizations are normally
  disabled, not deleted.
"""

