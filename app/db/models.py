"""SQLAlchemy models: metadata only.

No table has a column for activation codes, matching IDs, confirmation codes,
uploaded files, PDFs, customer names or customer emails. Codes are only ever
stored as HMAC fingerprints (``code_fingerprints``, see ``app.db.fingerprints``).

Conventions:

- Primary keys are ``BIGINT GENERATED BY DEFAULT AS IDENTITY``.
- Times are ``timestamptz`` (UTC) with ``now()`` server defaults; ``usage.day`` is a UTC date.
- Enumerations are ``VARCHAR`` + ``CHECK`` (not native PG enums), so adding a value
  is a plain constraint change.
- Token and fingerprint columns hold 32-byte digests (``CHECK octet_length = 32``).
- ``ON DELETE`` is enforced by the database (no ORM cascades): data owned by an
  organization is deleted with it, a user's sessions are deleted with the user,
  and history (batches, audit log, who invited / handled what) survives with the
  user or organization reference set to NULL. Organizations are normally
  disabled, not deleted.
"""

from __future__ import annotations

import datetime as dt
import enum
from ipaddress import IPv4Network, IPv6Network
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Identity,
    Index,
    Integer,
    LargeBinary,
    String,
    Text,
    UniqueConstraint,
    false,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import CIDR
from sqlalchemy.orm import Mapped, MappedColumn, mapped_column

from app.db.base import Base
from app.db.ip import IPV4_PREFIX_LEN, IPV6_PREFIX_LEN

DEFAULT_DAILY_ROW_QUOTA = 20_000
DIGEST_BYTES = 32  # SHA-256 / HMAC-SHA256
MAX_EMAIL_CHARS = 254
MAX_NAME_CHARS = 200
MAX_NOTE_CHARS = 2000
MAX_ACTION_CHARS = 64
# Match app/web/routes.py (MAX_COMPANY_CHARS, MAX_FOOTER_CHARS, MAX_LOGO_BYTES).
MAX_BRANDING_COMPANY_CHARS = 100
MAX_BRANDING_FOOTER_CHARS = 200
MAX_LOGO_BYTES = 500 * 1024
PNG_SIGNATURE_HEX = "89504e470d0a1a0a"
DEFAULT_PRIMARY_HEX = "#000000"


class Role(enum.StrEnum):
    OWNER = "owner"
    MEMBER = "member"


class AccessRequestStatus(enum.StrEnum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"


class VolumeBand(enum.StrEnum):
    """Expected eSIMs per month, as chosen on the "Request access" form."""

    UNDER_1K = "under_1k"
    FROM_1K_TO_10K = "1k_10k"
    FROM_10K_TO_100K = "10k_100k"
    OVER_100K = "over_100k"


class FingerprintKind(enum.StrEnum):
    ICCID = "iccid"
    ACTIVATION = "activation"


class BatchStatus(enum.StrEnum):
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"


class AuditOutcome(enum.StrEnum):
    SUCCESS = "success"
    FAILURE = "failure"


def _enum(cls: type[enum.StrEnum], name: str) -> Enum:
    """``VARCHAR`` + ``CHECK`` storing the member values (``"owner"``, not ``"OWNER"``)."""
    return Enum(
        cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=16,
        values_callable=lambda members: [m.value for m in members],
        validate_strings=True,
    )


def _id() -> MappedColumn[int]:
    return mapped_column(BigInteger, Identity(), primary_key=True)


def _created_at(*, index: bool = False) -> MappedColumn[dt.datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), index=index)


def _fk(target: str, ondelete: str, *, nullable: bool, index: bool = False) -> MappedColumn[Any]:
    return mapped_column(
        BigInteger, ForeignKey(target, ondelete=ondelete), nullable=nullable, index=index
    )


def _digest_check(column: str) -> CheckConstraint:
    return CheckConstraint(f"octet_length({column}) = {DIGEST_BYTES}", name=f"{column}_length")


class Organization(Base):
    __tablename__ = "organizations"
    __table_args__ = (CheckConstraint("daily_row_quota >= 0", name="daily_row_quota_nonnegative"),)

    id: Mapped[int] = _id()
    name: Mapped[str] = mapped_column(String(MAX_NAME_CHARS))
    daily_row_quota: Mapped[int] = mapped_column(
        Integer, default=DEFAULT_DAILY_ROW_QUOTA, server_default=str(DEFAULT_DAILY_ROW_QUOTA)
    )
    disabled: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    created_at: Mapped[dt.datetime] = _created_at()


class User(Base):
    """A login. ``email`` is unique case-insensitively (``lower(email)`` index)."""

    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint(
            "is_superadmin OR organization_id IS NOT NULL",
            name="organization_required_unless_superadmin",
        ),
    )

    id: Mapped[int] = _id()
    email: Mapped[str] = mapped_column(String(MAX_EMAIL_CHARS))
    password_hash: Mapped[str | None] = mapped_column(Text)  # NULL until the invite is accepted
    organization_id: Mapped[int | None] = _fk(
        "organizations.id", "CASCADE", nullable=True, index=True
    )
    role: Mapped[Role] = mapped_column(_enum(Role, "role"), default=Role.MEMBER)
    is_superadmin: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    disabled: Mapped[bool] = mapped_column(Boolean, default=False, server_default=false())
    created_at: Mapped[dt.datetime] = _created_at()
    last_login_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))


Index("uq_users_email_lower", func.lower(User.email), unique=True)


class Invite(Base):
    __tablename__ = "invites"
    __table_args__ = (_digest_check("token_hash"),)

    id: Mapped[int] = _id()
    token_hash: Mapped[bytes] = mapped_column(LargeBinary, unique=True)
    email: Mapped[str] = mapped_column(String(MAX_EMAIL_CHARS))
    organization_id: Mapped[int] = _fk("organizations.id", "CASCADE", nullable=False, index=True)
    role: Mapped[Role] = mapped_column(_enum(Role, "role"), default=Role.MEMBER)
    expires_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True))
    used_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))
    created_by: Mapped[int | None] = _fk("users.id", "SET NULL", nullable=True)
    created_at: Mapped[dt.datetime] = _created_at()


class PasswordToken(Base):
    """A one-time set-password link for an existing user (reset, or a superadmin's first
    password). Only the SHA-256 of the random token is stored."""

    __tablename__ = "password_tokens"
    __table_args__ = (_digest_check("token_hash"),)

    id: Mapped[int] = _id()
    token_hash: Mapped[bytes] = mapped_column(LargeBinary, unique=True)
    user_id: Mapped[int] = _fk("users.id", "CASCADE", nullable=False, index=True)
    expires_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True))
    used_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[dt.datetime] = _created_at()


class UserSession(Base):
    """A login session. Only hashes of the session and CSRF tokens are stored."""

    __tablename__ = "sessions"
    __table_args__ = (_digest_check("token_hash"), _digest_check("csrf_token_hash"))

    id: Mapped[int] = _id()
    token_hash: Mapped[bytes] = mapped_column(LargeBinary, unique=True)
    user_id: Mapped[int] = _fk("users.id", "CASCADE", nullable=False, index=True)
    csrf_token_hash: Mapped[bytes] = mapped_column(LargeBinary)
    created_at: Mapped[dt.datetime] = _created_at()
    expires_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), index=True)
    last_seen_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )


class AccessRequest(Base):
    """A "Request access" form submission (the requester's details, kept 30 days)."""

    __tablename__ = "access_requests"
    __table_args__ = (
        CheckConstraint(f"char_length(note) <= {MAX_NOTE_CHARS}", name="note_length"),
    )

    id: Mapped[int] = _id()
    company_name: Mapped[str] = mapped_column(String(MAX_NAME_CHARS))
    contact_name: Mapped[str] = mapped_column(String(MAX_NAME_CHARS))
    email: Mapped[str] = mapped_column(String(MAX_EMAIL_CHARS))
    volume_band: Mapped[VolumeBand] = mapped_column(_enum(VolumeBand, "volume_band"))
    note: Mapped[str | None] = mapped_column(Text)
    status: Mapped[AccessRequestStatus] = mapped_column(
        _enum(AccessRequestStatus, "status"),
        default=AccessRequestStatus.PENDING,
        server_default=AccessRequestStatus.PENDING.value,
        index=True,
    )
    created_at: Mapped[dt.datetime] = _created_at(index=True)
    handled_at: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True))
    handled_by: Mapped[int | None] = _fk("users.id", "SET NULL", nullable=True)


class Branding(Base):
    """One per organization. ``logo_png`` must be a PNG (signature checked) of at most
    ``MAX_LOGO_BYTES``."""

    __tablename__ = "branding"
    __table_args__ = (
        CheckConstraint("primary_hex ~ '^#[0-9A-Fa-f]{6}$'", name="primary_hex_format"),
        CheckConstraint(f"octet_length(logo_png) <= {MAX_LOGO_BYTES}", name="logo_png_size"),
        CheckConstraint(
            f"substring(logo_png FROM 1 FOR 8) = decode('{PNG_SIGNATURE_HEX}', 'hex')",
            name="logo_png_signature",
        ),
    )

    organization_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("organizations.id", ondelete="CASCADE"), primary_key=True
    )
    company_name: Mapped[str] = mapped_column(String(MAX_BRANDING_COMPANY_CHARS))
    primary_hex: Mapped[str] = mapped_column(
        String(7), default=DEFAULT_PRIMARY_HEX, server_default=DEFAULT_PRIMARY_HEX
    )
    footer_text: Mapped[str] = mapped_column(
        String(MAX_BRANDING_FOOTER_CHARS), default="", server_default=""
    )
    logo_png: Mapped[bytes | None] = mapped_column(LargeBinary)
    updated_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class Batch(Base):
    """One upload's outcome: counts only, never row data."""

    __tablename__ = "batches"
    __table_args__ = (
        CheckConstraint(
            "row_count >= 0 AND parts >= 0 AND error_count >= 0 AND warning_count >= 0",
            name="counts_nonnegative",
        ),
        Index("ix_batches_organization_id_created_at", "organization_id", "created_at"),
    )

    id: Mapped[int] = _id()
    organization_id: Mapped[int] = _fk("organizations.id", "CASCADE", nullable=False)
    user_id: Mapped[int | None] = _fk("users.id", "SET NULL", nullable=True, index=True)
    created_at: Mapped[dt.datetime] = _created_at()
    row_count: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
    parts: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
    error_count: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
    warning_count: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
    status: Mapped[BatchStatus] = mapped_column(
        _enum(BatchStatus, "status"),
        default=BatchStatus.RUNNING,
        server_default=BatchStatus.RUNNING.value,
    )


class CodeFingerprint(Base):
    """HMAC-SHA256 of an ICCID or activation code (``app.db.fingerprints``), never the code."""

    __tablename__ = "code_fingerprints"
    __table_args__ = (
        UniqueConstraint("organization_id", "kind", "fingerprint"),
        _digest_check("fingerprint"),
    )

    id: Mapped[int] = _id()
    organization_id: Mapped[int] = _fk("organizations.id", "CASCADE", nullable=False)
    kind: Mapped[FingerprintKind] = mapped_column(_enum(FingerprintKind, "kind"))
    fingerprint: Mapped[bytes] = mapped_column(LargeBinary)
    batch_id: Mapped[int] = _fk("batches.id", "CASCADE", nullable=False, index=True)
    created_at: Mapped[dt.datetime] = _created_at()


class AuditLog(Base):
    """Security events (kept 90 days). No free-text details; ``ip_prefix`` is /24 or /48."""

    __tablename__ = "audit_log"
    __table_args__ = (
        CheckConstraint(
            f"(family(ip_prefix) = 4 AND masklen(ip_prefix) = {IPV4_PREFIX_LEN})"
            f" OR (family(ip_prefix) = 6 AND masklen(ip_prefix) = {IPV6_PREFIX_LEN})",
            name="ip_prefix_length",
        ),
        Index("ix_audit_log_organization_id_created_at", "organization_id", "created_at"),
    )

    id: Mapped[int] = _id()
    created_at: Mapped[dt.datetime] = _created_at(index=True)
    user_id: Mapped[int | None] = _fk("users.id", "SET NULL", nullable=True, index=True)
    # The user the action was done to (disabled, invited, sent a reset link), if any.
    target_user_id: Mapped[int | None] = _fk("users.id", "SET NULL", nullable=True, index=True)
    organization_id: Mapped[int | None] = _fk("organizations.id", "SET NULL", nullable=True)
    action: Mapped[str] = mapped_column(String(MAX_ACTION_CHARS))
    outcome: Mapped[AuditOutcome] = mapped_column(_enum(AuditOutcome, "outcome"))
    ip_prefix: Mapped[IPv4Network | IPv6Network | None] = mapped_column(CIDR)


class Usage(Base):
    """Rows generated per organization per UTC day (for the daily quota)."""

    __tablename__ = "usage"
    __table_args__ = (CheckConstraint("rows_generated >= 0", name="rows_generated_nonnegative"),)

    organization_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("organizations.id", ondelete="CASCADE"), primary_key=True
    )
    day: Mapped[dt.date] = mapped_column(Date, primary_key=True)
    rows_generated: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
