"""Measure /validate's duplicate check against a large code_fingerprints table.

Usage (from the repo root; needs TEST_DATABASE_URL in .env):
    .venv\\Scripts\\python.exe scripts\\bench_duplicates.py
    .venv\\Scripts\\python.exe scripts\\bench_duplicates.py --fingerprints 1000000 --rows 10000

What it does, on the TEST database only (it refuses to run when TEST_DATABASE_URL is
the DATABASE_URL database), which it empties first and again at the end:

1. Adds ``--fingerprints`` synthetic fingerprints (random-looking 32-byte digests made
   from md5 in SQL, spread over 200 batches and the last 300 days) for the organization
   under test, plus 10% as many for a second organization, then ANALYZE.
2. Builds a synthetic ``--rows``-row CSV in memory (``make_big_csv.make_csv``).
3. Times the duplicate check (HMAC of every ICCID and activation code + the lookup
   queries) and the whole POST /validate request, first when no row was used before,
   then when every row was (all of them generated by an earlier batch).

Prints timings only. Keys are random per run; nothing is written outside the database.
"""

from __future__ import annotations

import argparse
import secrets
import statistics
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from alembic import command  # noqa: E402
from alembic.config import Config  # noqa: E402
from fastapi.testclient import TestClient  # noqa: E402
from make_big_csv import make_csv  # noqa: E402
from sqlalchemy import Engine, text  # noqa: E402
from sqlalchemy.engine import make_url  # noqa: E402
from sqlalchemy.orm import Session, sessionmaker  # noqa: E402

from app import batches  # noqa: E402
from app.auth import accounts  # noqa: E402
from app.auth.passwords import hash_password  # noqa: E402
from app.auth.tokens import csrf_for  # noqa: E402
from app.core.pipeline import check_upload, part_count  # noqa: E402
from app.db.base import Base  # noqa: E402
from app.db.engine import make_engine  # noqa: E402
from app.db.models import Organization, Role, User  # noqa: E402
from app.settings import Secret, Settings, get_settings  # noqa: E402
from app.web.auth import CSRF_HEADER, SESSION_COOKIE  # noqa: E402
from app.web.main import create_app  # noqa: E402

BATCHES = 200


def test_engine() -> Engine:
    settings = get_settings()
    if settings.test_database_url is None:
        sys.exit("TEST_DATABASE_URL is not set (see README, Database).")
    test_url = make_url(settings.test_database_url.reveal())
    if settings.database_url is not None:
        dev_url = make_url(settings.database_url.reveal())
        if (test_url.host, test_url.port, test_url.database) == (
            dev_url.host,
            dev_url.port,
            dev_url.database,
        ):
            sys.exit("TEST_DATABASE_URL points at the DATABASE_URL database; refusing to run.")
    engine = make_engine(settings.test_database_url.reveal())
    with engine.begin() as conn:
        cfg = Config(str(ROOT / "alembic.ini"))
        cfg.attributes["connection"] = conn
        cfg.attributes["configure_logger"] = False
        command.upgrade(cfg, "head")
    return engine


def empty(engine: Engine) -> None:
    tables = ", ".join(t.name for t in Base.metadata.sorted_tables)
    with engine.begin() as conn:
        conn.execute(text(f"TRUNCATE {tables} RESTART IDENTITY CASCADE"))


def seed(engine: Engine, sessions: sessionmaker[Session], fingerprints: int) -> tuple[int, int]:
    """The organization and user under test; ``fingerprints`` rows for that organization."""
    empty(engine)
    with sessions.begin() as db:
        org, other = Organization(name="Bench Org (synthetic)"), Organization(name="Other")
        db.add_all([org, other])
        db.flush()
        user = User(
            email="bench@org.test",
            organization_id=org.id,
            role=Role.OWNER,
            password_hash=hash_password(secrets.token_urlsafe(32)),  # never used to log in
        )
        db.add(user)
        db.flush()
        org_id, other_id, user_id = org.id, other.id, user.id
    with engine.begin() as conn:
        for owner, count, salt in (
            (org_id, fingerprints, "a"),
            (other_id, fingerprints // 10, "b"),
        ):
            first = conn.execute(
                text(
                    "INSERT INTO batches (organization_id, file_name, row_count, parts,"
                    " parts_downloaded, status, created_at)"
                    " SELECT :org, 'bench_' || g || '.csv', 5000, 10, 10, 'completed',"
                    " now() - (g % 300) * interval '1 day'"
                    " FROM generate_series(1, :n) g RETURNING id"
                ),
                {"org": owner, "n": BATCHES},
            ).all()
            batch_ids = sorted(r[0] for r in first)
            conn.execute(
                text(
                    "INSERT INTO code_fingerprints"
                    " (organization_id, kind, fingerprint, batch_id, created_at)"
                    " SELECT :org,"
                    " CASE WHEN g % 2 = 0 THEN 'iccid' ELSE 'activation' END,"
                    " decode(md5(:salt || g) || md5(:salt || '-' || g), 'hex'),"
                    " :first + (g % :batches),"
                    " now() - (g % 300) * interval '1 day'"
                    " FROM generate_series(1, :n) g"
                ),
                {
                    "org": owner,
                    "salt": salt,
                    "first": batch_ids[0],
                    "batches": BATCHES,
                    "n": count,
                },
            )
        conn.execute(text("ANALYZE code_fingerprints"))
        conn.execute(text("ANALYZE batches"))
    return org_id, user_id


def median_ms(fn, repeat: int) -> tuple[float, object]:
    times, result = [], None
    for _ in range(repeat):
        start = time.perf_counter()
        result = fn()
        times.append((time.perf_counter() - start) * 1000)
    return statistics.median(times), result


def main() -> int:
    args = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    args.add_argument("--fingerprints", type=int, default=1_000_000)
    args.add_argument("--rows", type=int, default=10_000)
    args.add_argument("--repeat", type=int, default=5)
    opts = args.parse_args()

    engine = test_engine()
    sessions = sessionmaker(bind=engine, expire_on_commit=False)
    key = secrets.token_urlsafe(48)
    settings = Settings(
        env="development",
        database_url=Secret(engine.url.render_as_string(hide_password=False)),
        secret_key=Secret(secrets.token_urlsafe(48)),
        fingerprint_key=Secret(key),
        public_base_url="http://testserver",
    )
    key_bytes = key.encode()
    try:
        started = time.perf_counter()
        org_id, user_id = seed(engine, sessions, opts.fingerprints)
        with engine.connect() as conn:
            total = conn.execute(text("SELECT count(*) FROM code_fingerprints")).scalar_one()
        print(f"seeded {total:,} fingerprints in {time.perf_counter() - started:.1f} s")  # noqa: T201

        data = make_csv(opts.rows)
        parse_ms, (parsed, report) = median_ms(lambda: check_upload(data, "bench.csv"), opts.repeat)
        records = report.valid
        print(f"file: {len(parsed.records):,} rows, {len(data) / 1e6:.1f} MB")  # noqa: T201
        print(f"parse + validate (no database):       {parse_ms:8.1f} ms")  # noqa: T201
        hmac_ms, _ = median_ms(lambda: batches._digests(org_id, records, key_bytes), opts.repeat)
        print(f"HMAC of {2 * len(records):,} values:            {hmac_ms:8.1f} ms")  # noqa: T201

        def check() -> batches.UsedCheck:
            now = datetime.now(UTC)
            with sessions.begin() as db:
                return batches.find_used(db, org_id, records, key=key_bytes, now=now)

        app = create_app(settings, sessions=sessions, run_retention=False)
        with sessions.begin() as db:
            token = accounts.create_session(db, user_id, now=datetime.now(UTC))
        client = TestClient(app, follow_redirects=False)
        client.cookies.set(SESSION_COOKIE, token)
        client.headers[CSRF_HEADER] = csrf_for(token)

        def validate() -> int:
            files = {"file": ("bench.csv", data, "text/csv")}
            return client.post("/validate", files=files).status_code

        for label in ("no row used before", "every row used before"):
            check_ms, result = median_ms(check, opts.repeat)
            if not isinstance(result, batches.UsedCheck):
                raise TypeError("unexpected result")
            hits = len(result.issues)
            print(f"\n{label}:")  # noqa: T201
            print(f"  duplicate check (HMAC + lookups):   {check_ms:8.1f} ms  ({hits:,} errors)")  # noqa: T201
            print(f"    of which lookups:                 {check_ms - hmac_ms:8.1f} ms")  # noqa: T201
            route_ms, status = median_ms(validate, opts.repeat)
            print(f"  POST /validate, whole request:      {route_ms:8.1f} ms  (HTTP {status})")  # noqa: T201
            if label.startswith("no row"):
                # An earlier batch generates every row of the file.
                with sessions.begin() as db:
                    batch_id = batches.create_batch(
                        db,
                        organization_id=org_id,
                        user_id=user_id,
                        file_name="earlier.csv",
                        row_count=len(records),
                        parts=part_count(len(records)),
                        warning_count=0,
                        now=datetime.now(UTC),
                    )
                    batches._add_fingerprints(
                        db, org_id, batch_id, records, key=key_bytes, now=datetime.now(UTC)
                    )
                with engine.begin() as conn:
                    conn.execute(text("ANALYZE code_fingerprints"))

        with engine.connect() as conn:
            digests = list(batches._digests(org_id, records, key_bytes)[batches._KINDS[0][0]])
            digests = digests[: batches.LOOKUP_CHUNK]  # one query, as find_used sends it
            plan = conn.execute(
                text(
                    "EXPLAIN (ANALYZE, BUFFERS OFF) SELECT f.fingerprint FROM code_fingerprints f"
                    " JOIN batches b ON b.id = f.batch_id WHERE f.organization_id = :org"
                    " AND f.kind = 'iccid' AND f.fingerprint = ANY(:fps)"
                    " AND f.created_at >= now() - interval '365 days'"
                ),
                {"org": org_id, "fps": digests},
            ).all()
        print(f"\nplan of one lookup query ({len(digests):,} ICCID fingerprints, all used):")  # noqa: T201
        for (line,) in plan:
            if any(word in line for word in ("Scan", "Join", "Execution", "Planning")):
                print("  " + line.strip())  # noqa: T201
    finally:
        empty(engine)
        engine.dispose()
    return 0


if __name__ == "__main__":
    sys.exit(main())
